// Fork-owned (auto-mass-logging): builds app/js/fork/fit-mass-data.js, the static list of fittable modules that
// change a ship's mass, from CCP's public ESI (no token). Re-run when CCP adds plates / prop modules / rigs:
//   node tools/fork/build-fit-mass-data.mjs > app/js/fork/fit-mass-data.js
// then rebuild the JS bundle. Needs Node 18+ (fetch). About 220 public requests, run by hand, never at runtime.
//
// Dogma behind it (checked against ESI /dogma/effects):
// - Armor plates (group 329): effect armorReinforcerMassAdd adds massAddition (attribute 796) to ship mass, always.
// - Afterburners / MWDs (group 46): massAddition is added only while the module is active (moduleBonusAfterburner /
//   moduleBonusMicrowarpdrive), i.e. a "hot" jump.
// - Higgs anchor rigs (group 1308): effect massReductionBonusPassive post-percents ship mass by massBonusPercentage
//   (attribute 1131, +100% = x2).
// - A fitted item's own `mass` (e.g. T3 subsystems' 1,400 t) is not added to the ship: the subSystem effect has no
//   mass modifier, and the strategic cruiser hull mass already includes it.
const ESI = 'https://esi.evetech.net/latest';
const UA = 'Tripwire fork fit-mass-data builder';
const GROUPS = { prop: 46, plate: 329, rigAnchor: 1308 };
const MASS_ADDITION = 796, MASS_BONUS_PERCENTAGE = 1131;

async function get(path) {
	for (let attempt = 0; attempt < 3; attempt++) {
		const res = await fetch(ESI + path, { headers: { 'User-Agent': UA } });
		if (res.ok) { return res.json(); }
		await new Promise(r => setTimeout(r, 1000 * (attempt + 1)));
	}
	throw new Error('ESI request failed: ' + path);
}

const types = {};
for (const [kind, groupID] of Object.entries(GROUPS)) {
	const group = await get(`/universe/groups/${groupID}/`);
	for (const typeID of group.types) {
		const t = await get(`/universe/types/${typeID}/`);
		if (!t.published) { continue; }
		const attrs = {};
		(t.dogma_attributes || []).forEach(a => { attrs[a.attribute_id] = a.value; });
		const entry = { n: t.name };
		if (kind === 'rigAnchor') {
			if (!attrs[MASS_BONUS_PERCENTAGE]) { continue; }
			entry.x = 1 + attrs[MASS_BONUS_PERCENTAGE] / 100;
		} else {
			if (!(attrs[MASS_ADDITION] > 0)) { continue; }
			entry.a = attrs[MASS_ADDITION];
			if (kind === 'prop') { entry.p = 1; }
		}
		types[typeID] = entry;
	}
}

const ids = Object.keys(types).map(Number).sort((a, b) => a - b);
const lines = ids.map(id => '\t\t' + id + ': ' + JSON.stringify(types[id]));
process.stdout.write(
	'const fitMassData = {\n' +
	'\t// Generated by tools/fork/build-fit-mass-data.mjs from public ESI on ' + new Date().toISOString().slice(0, 10) + '; do not edit by hand.\n' +
	'\t// Modules that change ship mass. n: name, a: massAddition in kg (always for plates; only while active for\n' +
	'\t// propulsion modules, p: 1), x: ship mass multiplier (Higgs anchor rigs). Any other fitted type leaves mass alone.\n' +
	'\ttypes: {\n' + lines.join(',\n') + '\n\t}\n' +
	'};\n');
