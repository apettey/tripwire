// Fork-owned: regenerates discord/gate_graph.php, the static system data and stargate graph the Discord
// notifications use server-side (names, security, regions, gate jumps to the ping systems). Source: appData in
// public/js/combine.js (systems, regions, map.shortest), the same data the browser routes with. Run after
// upstream updates combine.js:
//   docker compose -f docker-compose.dev.yml exec -T assets node discord/tools/generate-gate-graph.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..', '..');
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'public/js/combine.js'), 'utf8') + '\nthis.appData = appData;', context);
const appData = context.appData;

const ids = Object.keys(appData.systems).map(Number)
	.filter((id) => Number.isInteger(id) && id >= 30000000 && id < 33000000)
	.sort((a, b) => a - b);

// Same rules as app/js/fork/favourites-panel.js: k-space = no wormhole class and outside the wormhole regions
// (Pochven counts); high-sec = k-space, not Pochven (faction 500026), security >= 0.45 (systemAnalysis)
const flags = (s) => {
	const kspace = !s.class && (Number(s.regionID) || 0) < 11000000;
	const highsec = kspace && s.factionID != 500026 && Number(s.security) >= 0.45;
	const pochven = s.factionID == 500026;
	return (kspace ? 1 : 0) | (highsec ? 2 : 0) | (pochven ? 4 : 0);
};
const q = (text) => "'" + String(text).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

const lines = [];
let gates = 0;
for (const id of ids) {
	const s = appData.systems[id];
	const next = Object.keys((appData.map.shortest || {})[id - 30000000] || {}).map((k) => 30000000 + Number(k))
		.filter((n) => appData.systems[n]).sort((a, b) => a - b);
	gates += next.length;
	const cls = Array.isArray(s.class) ? s.class[0] : (s.class || 0);
	lines.push(id + '=>[' + q(s.name) + ',' + Number(Number(s.security).toFixed(3)) + ',' + (Number(s.regionID) || 0) + ','
		+ flags(s) + ',' + (Number(cls) || 0) + ',[' + next.join(',') + ']]');
}
const regions = Object.keys(appData.regions || {}).map(Number).sort((a, b) => a - b)
	.map((id) => id + '=>' + q(appData.regions[id].name));

const out = "<?php\n// Generated by discord/tools/generate-gate-graph.js from public/js/combine.js; do not edit.\n"
	+ '// ' + ids.length + ' solar systems, ' + gates + ' gate links (both directions), ' + regions.length + ' regions.\n'
	+ '// systems: id => [name, security, regionID, flags (1 k-space, 2 high-sec, 4 Pochven), wormhole class, [gate neighbours]]\n'
	+ "return ['systems' => [\n" + lines.join(",\n") + "\n], 'regions' => [\n" + regions.join(",\n") + "\n]];\n";
fs.writeFileSync(path.join(root, 'discord/gate_graph.php'), out);
console.log('discord/gate_graph.php: ' + ids.length + ' systems, ' + gates + ' gate links, ' + regions.length + ' regions');
