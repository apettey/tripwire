// Fork-owned: regenerates zkill/system_ids.php, the solar system IDs the zKillboard integration accepts
// (endpoints refuse to queue back-fills for anything else). Source: appData.systems in public/js/combine.js,
// the same static data the browser uses. Run after upstream updates combine.js:
//   docker compose -f docker-compose.dev.yml exec -T assets node zkill/tools/generate-system-ids.js
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.join(__dirname, '..', '..');
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'public/js/combine.js'), 'utf8') + '\nthis.appData = appData;', context);
const ids = Object.keys(context.appData.systems).map(Number)
	.filter((id) => Number.isInteger(id) && id >= 30000000 && id < 33000000)
	.sort((a, b) => a - b);

// Consecutive IDs as ranges: "30000001-30005005,31000001-31002605,..."
const ranges = [];
for (const id of ids) {
	const last = ranges[ranges.length - 1];
	if (last && id === last[1] + 1) { last[1] = id; } else { ranges.push([id, id]); }
}
const text = ranges.map(([a, b]) => (a === b ? String(a) : a + '-' + b)).join(',');
const out = "<?php\n// Generated by zkill/tools/generate-system-ids.js from public/js/combine.js; do not edit.\n"
	+ '// ' + ids.length + ' solar systems in ' + ranges.length + ' ranges.\n'
	+ "return '" + text + "';\n";
fs.writeFileSync(path.join(root, 'zkill/system_ids.php'), out);
console.log('zkill/system_ids.php: ' + ids.length + ' systems, ' + ranges.length + ' ranges');
